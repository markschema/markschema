import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const __filename = fileURLToPath(import.meta.url)
const __dirname = dirname(__filename)

const repoRoot = resolve(__dirname, '../../..')
const sourcePath = resolve(repoRoot, 'packages/mdshape/dist/index.d.ts')
const targetPath = resolve(repoRoot, 'apps/playground/src/lib/monaco-mdshape-dts.ts')

const source = readFileSync(sourcePath, 'utf8')

const content = `/* Auto-generated by apps/playground/scripts/generate-monaco-mdshape-dts.mjs */

export const MONACO_MDSHAPE_PACKAGE_DTS = ${JSON.stringify(`declare module '@markschema/mdshape' {\n${source}\n}\n`)}

export const MONACO_MDSHAPE_ALIAS_DTS = ${JSON.stringify(`declare module 'mdshape' {\n  export * from '@markschema/mdshape'\n}\n`)}
`

mkdirSync(dirname(targetPath), { recursive: true })
writeFileSync(targetPath, content, 'utf8')

console.log('generated', targetPath)
